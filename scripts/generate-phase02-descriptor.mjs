import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..')
const generatedRoot = join(repoRoot, 'app-v2', 'src', 'main', 'phase02', 'generated')
const bufBinary = process.env.BUF_BIN || (process.platform === 'win32' ? 'buf.exe' : 'buf')

function generate(inputRoot, outputName, constantPrefix) {
  const outputPath = join(generatedRoot, outputName)
  const scratchPath = join(repoRoot, `.phase02-descriptor-${constantPrefix}-${process.pid}.binpb`)
  rmSync(scratchPath, { force: true })
  const result = spawnSync(
    bufBinary,
    [
      'build',
      inputRoot,
      '--as-file-descriptor-set',
      '--exclude-source-info',
      '--output',
      scratchPath
    ],
    { cwd: repoRoot, encoding: 'utf8', windowsHide: true }
  )
  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`${result.stdout || ''}${result.stderr || ''}`.trim())
  try {
    const bytes = readFileSync(scratchPath)
    const sha256 = createHash('sha256').update(bytes).digest('hex')
    const base64 = bytes.toString('base64')
    mkdirSync(dirname(outputPath), { recursive: true })
    writeFileSync(
      outputPath,
      [
        '// Generated by scripts/generate-phase02-descriptor.mjs. Do not edit.',
        `export const ${constantPrefix}_DESCRIPTOR_SHA256 = '${sha256}' as const`,
        `export const ${constantPrefix}_DESCRIPTOR_BASE64 = '${base64}' as const`,
        '',
        `export function ${constantPrefix.toLowerCase()}DescriptorBytes(): Uint8Array {`,
        `  return Uint8Array.from(Buffer.from(${constantPrefix}_DESCRIPTOR_BASE64, 'base64'))`,
        '}',
        ''
      ].join('\n'),
      'utf8'
    )
    console.log(JSON.stringify({ outputPath, sha256, bytes: bytes.length }))
  } finally {
    rmSync(scratchPath, { force: true })
  }
}

generate(join(repoRoot, 'contracts'), 'contract-descriptor.ts', 'PHASE02')
generate(join(repoRoot, 'contracts', 'n-1'), 'n1-contract-descriptor.ts', 'PHASE02_N1')
