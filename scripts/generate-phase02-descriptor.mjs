import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..')
const contractsRoot = join(repoRoot, 'contracts')
const outputPath = join(
  repoRoot,
  'app-v2',
  'src',
  'main',
  'phase02',
  'generated',
  'contract-descriptor.ts'
)
const scratchPath = join(repoRoot, `.phase02-descriptor-${process.pid}.binpb`)
const bufBinary = process.env.BUF_BIN || (process.platform === 'win32' ? 'buf.exe' : 'buf')

rmSync(scratchPath, { force: true })
const result = spawnSync(
  bufBinary,
  [
    'build',
    contractsRoot,
    '--as-file-descriptor-set',
    '--exclude-source-info',
    '--output',
    scratchPath
  ],
  { cwd: repoRoot, encoding: 'utf8', windowsHide: true }
)
if (result.error) throw result.error
if (result.status !== 0) {
  throw new Error(`${result.stdout || ''}${result.stderr || ''}`.trim())
}

try {
  const bytes = readFileSync(scratchPath)
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  const base64 = bytes.toString('base64')
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(
    outputPath,
    [
      '// Generated by scripts/generate-phase02-descriptor.mjs. Do not edit.',
      `export const PHASE02_DESCRIPTOR_SHA256 = '${sha256}' as const`,
      `export const PHASE02_DESCRIPTOR_BASE64 = '${base64}' as const`,
      '',
      'export function phase02DescriptorBytes(): Uint8Array {',
      "  return Uint8Array.from(Buffer.from(PHASE02_DESCRIPTOR_BASE64, 'base64'))",
      '}',
      ''
    ].join('\n'),
    'utf8'
  )
  console.log(JSON.stringify({ outputPath, sha256, bytes: bytes.length }))
} finally {
  rmSync(scratchPath, { force: true })
}
