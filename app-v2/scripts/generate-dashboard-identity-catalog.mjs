import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const target = resolve(root, 'src/shared/dashboard-identity-catalog.generated.ts')
const server = await createServer({
  root,
  appType: 'custom',
  logLevel: 'error',
  server: { middlewareMode: true }
})

try {
  const { ALL_VARIANTS } = await server.ssrLoadModule(
    '/src/renderer/src/views/dashboard/widget-catalog-data.ts'
  )
  const entries = ALL_VARIANTS
    .filter((variant) =>
      variant.type === 'overlaywidget' &&
      (typeof variant.widgetId === 'string' || typeof variant.hifiModuleId === 'string')
    )
    .flatMap((variant) => {
      const entry = {
        id: variant.id,
        type: 'overlaywidget',
        label: variant.label,
        ...(typeof variant.hifiModuleId === 'string' ? { name: variant.hifiModuleId } : {}),
        ...(typeof variant.binding === 'string' ? { binding: variant.binding } : {}),
        ...(typeof variant.widgetId === 'string' ? { widgetId: variant.widgetId } : {}),
        ...(typeof variant.hifiModuleId === 'string' ? { hifiModuleId: variant.hifiModuleId } : {})
      }
      if (typeof variant.binding !== 'string') return [entry]
      const { binding: _binding, ...unbound } = entry
      return [entry, unbound]
    })
    .sort((a, b) => a.id.localeCompare(b.id) || ('binding' in a ? 1 : 0) - ('binding' in b ? 1 : 0))
  const source = [
    '// Generated by scripts/generate-dashboard-identity-catalog.mjs. Do not edit manually.',
    `export const DASHBOARD_IDENTITY_CATALOG = ${JSON.stringify(entries, null, 2)} as const`,
    ''
  ].join('\n')
  await writeFile(target, source, 'utf8')
  console.log(`Generated ${entries.length} dashboard identity entries.`)
} finally {
  await server.close()
}
